"""Writes botassist_characters.txt: characters bots may play ("<class item id> <team> <InGameID>"; 1 TR, 2 CT), from the
server's Item.csv: every class item with a team, so bots look like any character of the game. InGameID is the class
number the game takes ("joinclass <InGameID>", HandleMenu_ChooseAppearance); an item id there falls back to the
team's default character.

Usage: python gen_characters.py"""
import csv
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ITEM_CSV = os.path.join(HERE, "..", "..", "server", "CSNZ_Server", "bin", "Data", "Item.csv")

rows = []
header = None
with open(ITEM_CSV, encoding="latin1") as f:
    for row in csv.reader(f):
        if row and row[0] == ";ID":
            header = [h.lstrip(";") for h in row]
            continue
        if not row or not row[0].isdigit() or len(row) < 5 or not header:
            continue
        r = dict(zip(header, row))
        team = r.get("Team", "").strip()
        res = r.get("recourcename", "").strip()
        if r.get("ClassName", "").strip() == "Class" and team in ("1", "2") and res:
            ingame = r.get("InGameID", "").strip()
            rows.append((int(row[0]), int(team), int(ingame) if ingame.isdigit() else 0, res))

with open(os.path.join(HERE, "botassist_characters.txt"), "w", encoding="ascii") as f:
    f.write("; characters bots play at random: <class item id> <team> (1 TR, 2 CT) <InGameID (joinclass number)>\n")
    f.write("; generated by gen_characters.py from Item.csv; delete lines to keep a character away from bots\n")
    for item_id, team, ingame, res in rows:
        f.write(f"{item_id} {team} {ingame} ; {res}\n")
print(len(rows), "characters:", {t: sum(1 for r in rows if r[1] == t) for t in (1, 2)})
