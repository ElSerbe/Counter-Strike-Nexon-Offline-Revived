"""Writes botassist_weapons.txt: every weapon bots may buy ("<item id> <category>"; 1 pistol, 2 shotgun, 3 SMG,
4 rifle, 5 machine gun), from the server's Item.csv. Mode-only tools (voxel building, hero-mode boxes, bare hands...)
are left out.

Usage: python gen_weapons.py"""
import csv
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
ITEM_CSV = os.path.join(HERE, "..", "..", "server", "CSNZ_Server", "bin", "Data", "Item.csv")
SKIP = re.compile(r"^(vxl|zhe|standalone|zsh_|zbs|monkeywpnset|hand|dummy)|toolbox|firstaid", re.I)

rows = []
with open(ITEM_CSV, encoding="latin1") as f:
    for row in csv.reader(f):
        if not row or not row[0].isdigit() or len(row) < 5:
            continue
        item_id, res, cls, cat = int(row[0]), row[2].strip(), row[3].strip(), row[4].strip()
        if cls == "Equipment" and cat in ("1", "2", "3", "4", "5") and res and not SKIP.search(res):
            rows.append((item_id, int(cat), res))

with open(os.path.join(HERE, "botassist_weapons.txt"), "w", encoding="ascii") as f:
    f.write("; weapons bots buy at random: <item id> <category> (1 pistol, 2 shotgun, 3 SMG, 4 rifle, 5 machine gun)\n")
    f.write("; generated by gen_weapons.py from Item.csv; delete lines to keep a weapon away from bots\n")
    for item_id, cat, res in rows:
        f.write(f"{item_id} {cat} ; {res}\n")
print(len(rows), "weapons:", {c: sum(1 for r in rows if r[1] == c) for c in range(1, 6)})
