"""Writes botassist_balance.txt: the starting point of the weapon balance (zombie modes, the room's option).

One line per weapon: "<class name> <group> <damage per second against zombies> ; <item name>".
- The class name is the weapon entity's ("weapon_" + Item.csv's resource name), what botassist sees in a player's hand.
- The group is the type times 10 plus 1 for slow-firing guns (1 pistol, 2 shotgun, 3 SMG, 4 rifle, 5 machine gun,
  11 melee): 40 automatic rifles, 41 snipers and other slow rifles... A weapon is evened out against its group.
- The damage per second is a guess from the shop's numbers: zombie_damage (the damage a hit does to a zombie, the
  shop's weapon page) times the shots per second read from the FiringSpeed bar (0-100). botassist corrects it with
  what it measures in matches (botassist_weapon_dps.txt) and scales it to the measured numbers. 0: no guess (melee).

Mode weapons (the hero's, Zombie Shelter's, voxel tools...) are left out: they're never evened out.

Usage: python gen_weapon_balance.py"""
import csv
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
ITEM_CSV = os.path.join(HERE, "..", "..", "server", "CSNZ_Server", "bin", "Data", "Item.csv")
SKIP = re.compile(r"^(vxl|zhe|standalone|zsh_|zbs|monkeywpnset|hand|dummy)|toolbox|firstaid|hero", re.I)
# Counter-Strike's own weapons whose entity isn't named after the item
ALIASES = {"elites": "weapon_elite", "deserteagle": "weapon_deagle", "usp45": "weapon_usp"}
COL_DAMAGE, COL_RATE, COL_ZOMBIE_DAMAGE = 21, 24, 49

# the FiringSpeed bar against the seconds between shots, from Counter-Strike's weapons (AWP 26: 1.45 s, Scout 48:
# 1.25 s, M3 54: 0.88 s, XM1014 83: 0.25 s, Glock 86, M249 90: 0.1 s, AK-47 91, MP5 92: 0.075 s)
RATE_POINTS = [(0, 2.0), (26, 1.45), (48, 1.25), (54, 0.88), (70, 0.5), (83, 0.25), (86, 0.15), (90, 0.1),
               (91, 0.09), (92, 0.075), (95, 0.06), (100, 0.04)]
SLOW = 0.35  # seconds between shots from which a gun is in its type's slow group


def interval(bar):
    for (a, ia), (b, ib) in zip(RATE_POINTS, RATE_POINTS[1:]):
        if a <= bar <= b:
            return ia + (ib - ia) * (bar - a) / (b - a)
    return RATE_POINTS[-1][1]


def first_number(cell):
    m = re.match(r"\s*(\d+(?:\.\d+)?)", cell or "")
    return float(m.group(1)) if m else 0.0


rows = {}
with open(ITEM_CSV, encoding="latin1") as f:
    for row in csv.reader(f):
        if not row or not row[0].isdigit() or len(row) <= COL_ZOMBIE_DAMAGE:
            continue
        res, cls, cat = row[2].strip(), row[3].strip(), row[4].strip()
        if not res or SKIP.search(res):
            continue
        key = ALIASES.get(res.lower(), "weapon_" + res.lower())
        if cls == "Equipment" and cat in ("1", "2", "3", "4", "5"):
            rate = first_number(row[COL_RATE])
            hit = first_number(row[COL_ZOMBIE_DAMAGE]) or first_number(row[COL_DAMAGE])
            gap = interval(rate)
            group = int(cat) * 10 + (1 if gap >= SLOW else 0)
            dps = hit / gap if hit > 0 and rate > 0 else 0.0
        elif cls in ("Equipment", "PeriodicItem") and cat == "11":
            group, dps = 110, 0.0
        else:
            continue
        rows.setdefault(key, (group, dps, row[1].strip()))

with open(os.path.join(HERE, "botassist_balance.txt"), "w", encoding="ascii", errors="replace") as f:
    f.write("; weapon balance (zombie modes, the room's option): <class name> <group> <damage/s guess> ; <item>\n")
    f.write("; group = type * 10 + 1 for slow guns (1 pistol, 2 shotgun, 3 SMG, 4 rifle, 5 machine gun, 11 melee)\n")
    f.write("; generated by gen_weapon_balance.py from Item.csv; botassist corrects the guesses with what it measures\n")
    for key, (group, dps, name) in sorted(rows.items()):
        f.write(f"{key} {group} {dps:.0f} ; {name}\n")
groups = {}
for g, _, _ in rows.values():
    groups[g] = groups.get(g, 0) + 1
print(len(rows), "weapons by group:", dict(sorted(groups.items())))
