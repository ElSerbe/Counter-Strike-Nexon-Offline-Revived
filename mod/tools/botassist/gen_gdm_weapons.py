"""Writes botassist_gdm_weapons.txt: the weapons Gun Deathmatch draws from ("<weapon id> <tier>"; 1 pistol, 2 shotgun, 3 SMG,
4 rifle, 5 machine gun, 6 sniper rifle), from the server's Item.csv. The mode's tables hold weapon ids (column 5 of Item.csv,
not item ids). Sniper rifles share category 4 with rifles in Item.csv, so they go by name.

Usage: python gen_gdm_weapons.py"""
import csv
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
ITEM_CSV = os.path.join(HERE, "..", "..", "server", "CSNZ_Server", "bin", "Data", "Item.csv")
SKIP = re.compile(r"^(vxl|zhe|standalone|zsh_|zbs|monkeywpnset|hand|dummy)|toolbox|firstaid|zhc$", re.I)
SNIPER = re.compile(r"^(awp|svd|m95|m24|m40|m82|as50|sl8|sg550|g3sg1|scout|xm2010|trg42|l115|wa2000|dragunov|vsk94|"
                    r"sv98|bendita|railcannon|crossbow|bow)", re.I)
# ids from 4000 on aren't bought by name (the game's own bots give them another way)
MAX_ID = 4000

weapons = {}
with open(ITEM_CSV, encoding="latin1") as f:
    for row in csv.reader(f):
        if not row or not row[0].isdigit() or len(row) < 6:
            continue
        res, cls, cat, wid = row[2].strip(), row[3].strip(), row[4].strip(), row[5].strip()
        if cls != "Equipment" or cat not in ("1", "2", "3", "4", "5") or not wid.isdigit() or not res or SKIP.search(res):
            continue
        if 0 < int(wid) < MAX_ID and int(wid) not in weapons:
            weapons[int(wid)] = (6 if cat == "4" and SNIPER.search(res) else int(cat), res)

with open(os.path.join(HERE, "botassist_gdm_weapons.txt"), "w", encoding="ascii", newline="\n") as f:
    f.write("; Gun Deathmatch's weapons: <weapon id> <tier> (1 pistol, 2 shotgun, 3 SMG, 4 rifle, 5 machine gun, 6 sniper rifle)\n")
    f.write("; generated by gen_gdm_weapons.py from Item.csv; delete lines to keep a weapon out of the mode\n")
    for wid, (tier, res) in sorted(weapons.items()):
        f.write(f"{wid} {tier} ; {res}\n")
tiers = [t for t, _ in weapons.values()]
print(len(weapons), "weapons:", {t: tiers.count(t) for t in range(1, 7)})
print("sniper rifles:", ", ".join(r for t, r in weapons.values() if t == 6))
